package org.example;

public class AllTypes {

    private int pInt;
    private Integer wInt;
    private long pLong;
    private Long wLong;
    private double pDouble;
    private Double wDouble;
    private boolean pBool;
    private Boolean wBool;
    private String str;

    public AllTypes() {
    }

    public int getPInt() { return pInt; }
    public void setPInt(int v) { this.pInt = v; }

    public Integer getWInt() { return wInt; }
    public void setWInt(Integer v) { this.wInt = v; }

    public long getPLong() { return pLong; }
    public void setPLong(long v) { this.pLong = v; }

    public Long getWLong() { return wLong; }
    public void setWLong(Long v) { this.wLong = v; }

    public double getPDouble() { return pDouble; }
    public void setPDouble(double v) { this.pDouble = v; }

    public Double getWDouble() { return wDouble; }
    public void setWDouble(Double v) { this.wDouble = v; }

    public boolean isPBool() { return pBool; }
    public void setPBool(boolean v) { this.pBool = v; }

    public Boolean getWBool() { return wBool; }
    public void setWBool(Boolean v) { this.wBool = v; }

    public String getStr() { return str; }
    public void setStr(String v) { this.str = v; }
}
